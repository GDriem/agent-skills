#!/usr/bin/env bash
# install.sh: install the skills in skills/ for each agent harness, as symlinks, with a backup of anything
# replaced. See README.md and adapters/.
# Works with the bash 3.2 that ships with macOS: no associative arrays, no mapfile, no ${x,,}.

set -euo pipefail

PROG=$(basename "$0")
# /bin/pwd -P, not the builtin: on a case-insensitive filesystem (macOS) the builtin keeps the case the path was
# typed with, and the symlink targets compared in ours() must match the case on disk. /bin/pwd uses getcwd().
SRC=$(cd -P "$(dirname "$0")" && /bin/pwd -P)
MARK='# generated by agent-skills install.sh'
BACKUP_ROOT="$HOME/.agent-skills-backup"
CLAUDE_DIR="$HOME/.claude/skills"
AGENTS_DIR="$HOME/.agents/skills"
GEMINI_DIR="$HOME/.gemini/commands"
ALL_HARNESSES="claude-code codex copilot gemini cursor"

usage() {
  cat <<EOF
Usage: $PROG [--harness H] [--retire-conflicts] [--dry-run] [--yes]
       $PROG [--harness H] --check
       $PROG [--harness H] --uninstall [--dry-run] [--yes]

  --harness H          claude-code, codex, copilot, gemini, cursor or all; repeatable or comma-separated.
                       Default: the harnesses whose CLI is on PATH (claude, codex, copilot, gemini,
                       cursor-agent)
  --check              compare what is installed with this checkout and report conflicts; changes nothing.
                       Exit code 1 if something needs fixing
  --retire-conflicts   also move old copies with the same name as a skill to the backup:
                       ~/.codex/skills/<n> and ~/.codex/prompts/<n>.md (codex, cursor),
                       ~/.claude/commands/<n>.md (claude-code)
  --uninstall          remove the links and generated files of this checkout, then restore from the
                       backup whatever had been moved away and is still missing
  --dry-run            print the actions, change nothing
  --yes                do not ask for confirmation (required when stdin is not a terminal)

Destinations: ~/.claude/skills (claude-code) and ~/.agents/skills (every other harness), plus
~/.gemini/commands/<n>.toml (gemini) and skills/<n>/agents/openai.yaml in this checkout (codex, git-ignored).
Anything replaced goes to ~/.agent-skills-backup/<timestamp>/<path under \$HOME>; nothing is deleted
without a backup.
EOF
}

die() { printf '%s: %s\n' "$PROG" "$1" >&2; exit "${2:-2}"; }

# ---------------------------------------------------------------------------------------------------
# Arguments

mode=install retire=0 dry=0 yes=0 harnesses=''
while [ $# -gt 0 ]; do
  case "$1" in
    --harness) harnesses="$harnesses ${2:-}"; shift 2 ;;
    --harness=*) harnesses="$harnesses ${1#*=}"; shift ;;
    --check) mode=check; shift ;;
    --uninstall) mode=uninstall; shift ;;
    --retire-conflicts) retire=1; shift ;;
    --dry-run) dry=1; shift ;;
    --yes|-y) yes=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
done
[ "$mode" = install ] || [ "$retire" = 0 ] || die "--retire-conflicts only goes with an install"

harnesses=$(printf '%s' "$harnesses" | tr ',' ' ')
if [ -z "${harnesses// /}" ]; then
  for pair in claude:claude-code codex:codex copilot:copilot gemini:gemini cursor-agent:cursor; do
    command -v "${pair%%:*}" >/dev/null 2>&1 && harnesses="$harnesses ${pair#*:}"
  done
  [ -n "$harnesses" ] || die "no harness found on PATH (claude, codex, copilot, gemini, cursor-agent); pass --harness"
fi
selected=''
for h in $harnesses; do
  case "$h" in
    all) selected=" $ALL_HARNESSES" ;;
    claude-code|codex|copilot|gemini|cursor) case "$selected " in *" $h "*) ;; *) selected="$selected $h" ;; esac ;;
    *) die "unknown harness: $h" ;;
  esac
done
has() { case "$selected " in *" $1 "*) return 0 ;; esac; return 1; }

skills=''
for d in "$SRC"/skills/*/; do
  [ -f "$d/SKILL.md" ] && skills="$skills $(basename "$d")"
done
[ -n "$skills" ] || die "no skills found under $SRC/skills"

dests=''
has claude-code && dests="$CLAUDE_DIR"
if has codex || has copilot || has gemini || has cursor; then dests="$dests $AGENTS_DIR"; fi

# ---------------------------------------------------------------------------------------------------
# Generated metadata

# First sentence of the description in the frontmatter.
skill_summary() {
  sed -n '/^description:/{s/^description: *//;s/\. .*$//;s/\.$//;p;q;}' "$SRC/skills/$1/SKILL.md"
}

display_name() { # pr-review-all -> PR Review All
  printf '%s\n' "$1" | tr '-' ' ' | awk '{ for (i = 1; i <= NF; i++) $i = (tolower($i) == "pr") ? "PR" : toupper(substr($i, 1, 1)) substr($i, 2); print }'
}

# Short text for pickers; any other skill falls back to the first sentence of its description.
short_description() {
  case "$1" in
    pr-review) echo 'Review one GitHub PR and post verified findings' ;;
    pr-ready) echo 'Check whether one reviewed GitHub PR is ready' ;;
    pr-fix) echo 'Fix the review feedback of one GitHub PR and push it' ;;
    pr-review-all) echo 'Review open GitHub PRs, one fresh agent per PR' ;;
    pr-ready-all) echo 'Check readiness of open PRs, one agent per PR' ;;
    pr-fix-all) echo 'Fix review feedback on several PRs, one agent per PR' ;;
    orchestrate) echo 'Split a multi-task prompt across fresh agents' ;;
    *) skill_summary "$1" ;;
  esac
}

# Codex: skills that launch a fleet of agents (the batch skills, orchestrate) only run when called by name.
openai_yaml() {
  local n=$1 implicit=true prompt="Use \$$n on the pull request."
  case "$n" in
    *-all) implicit=false prompt="Use \$$n on the open pull requests." ;;
    orchestrate) implicit=false prompt="Use \$$n to split these tasks across fresh agents." ;;
  esac
  printf '%s\n' "$MARK" \
    'interface:' \
    "  display_name: \"$(display_name "$n")\"" \
    "  short_description: \"$(short_description "$n" | sed 's/"/\\"/g')\"" \
    "  default_prompt: \"$prompt\"" \
    'policy:' \
    "  allow_implicit_invocation: $implicit"
}

# Gemini has no /<skill> invocation: a custom command activates the skill and forwards the arguments.
gemini_toml() {
  local n=$1
  printf '%s\n' "$MARK" \
    "description = \"$(skill_summary "$n" | sed 's/"/\\"/g')\"" \
    'prompt = """' \
    "Activate the \`$n\` skill and follow its instructions." \
    "The arguments for the skill are the text after this colon: {{args}}" \
    '"""'
}

is_generated() { [ -f "$1" ] && [ ! -L "$1" ] && head -n 1 "$1" | grep -qxF "$MARK"; }

# ---------------------------------------------------------------------------------------------------
# Actions. Each one prints a line; with DRY=1 that is all it does.

STAMP=$(date '+%Y-%m-%dT%H-%M-%S')
BACKUP="$BACKUP_ROOT/$STAMP"
DRY=1 changes=0

say() { printf '  %-9s %s\n' "$1" "$2"; changes=$((changes + 1)); }
short() { case "$1" in "$HOME"/*) printf '~/%s' "${1#"$HOME"/}" ;; *) printf '%s' "$1" ;; esac; }
exists() { [ -e "$1" ] || [ -L "$1" ]; }
ours() { [ -L "$1" ] && [ "$(readlink "$1")" = "$SRC/skills/$2" ]; }

backup() { # <path> <reason>
  local rel=${1#"$HOME"/}
  case "$1" in "$HOME"/*) ;; *) die "refusing to back up a path outside \$HOME: $1" ;; esac
  say backup "$(short "$1") -> $(short "$BACKUP")/$rel ($2)"
  [ "$DRY" = 1 ] && return 0
  mkdir -p "$(dirname "$BACKUP/$rel")"
  mv "$1" "$BACKUP/$rel"
  printf '%s\t%s\n' "$1" "$2" >> "$BACKUP/manifest.tsv"
}

link() { # <dest dir> <skill>
  local target="$1/$2"
  ours "$target" "$2" && return 0
  exists "$target" && backup "$target" "replaced by the $2 skill"
  say link "$(short "$target") -> $SRC/skills/$2"
  [ "$DRY" = 1 ] && return 0
  mkdir -p "$1"
  ln -s "$SRC/skills/$2" "$target"
}

generate() { # <path> <content>
  if [ -f "$1" ] && [ "$(cat "$1")" = "$2" ]; then return 0; fi
  if exists "$1" && ! is_generated "$1"; then backup "$1" "replaced by a generated file"; fi
  say generate "$(short "$1")"
  [ "$DRY" = 1 ] && return 0
  mkdir -p "$(dirname "$1")"
  printf '%s\n' "$2" > "$1"
}

removed=''
remove() { # <path> (only links and generated files of this checkout)
  say remove "$(short "$1")"
  removed="$removed|$1|"
  [ "$DRY" = 1 ] && return 0
  rm -f "$1"
  case "$1" in */agents/openai.yaml) rmdir "$(dirname "$1")" 2>/dev/null || true ;; esac
}

# Present now and not removed earlier in this run (the plan pass removes nothing).
occupied() { exists "$1" && case "$removed" in *"|$1|"*) return 1 ;; esac; }

# Old copies with the same name as a skill: <path>|<harness that reads it>|<why>
conflicts() {
  local n=$1
  printf '%s\n' "$HOME/.codex/skills/$n|codex cursor|Codex still loads ~/.codex/skills and mixes it with the skill" \
    "$HOME/.codex/prompts/$n.md|codex|deprecated Codex custom prompt" \
    "$HOME/.claude/commands/$n.md|claude-code|old command; the skill wins over a command with the same name"
}

do_install() {
  local n d row path who why
  for n in $skills; do
    for d in $dests; do link "$d" "$n"; done
    if has codex; then generate "$SRC/skills/$n/agents/openai.yaml" "$(openai_yaml "$n")"; fi
    if has gemini; then generate "$GEMINI_DIR/$n.toml" "$(gemini_toml "$n")"; fi
    if [ "$retire" = 1 ]; then
      while IFS='|' read -r path who why; do
        for h in $who; do
          if has "$h" && exists "$path"; then backup "$path" "retired: $why"; break; fi
        done
      done <<EOF
$(conflicts "$n")
EOF
    fi
  done
  return 0
}

do_uninstall() {
  local n d entry path rest rel restored='' manifest bdir
  for n in $skills; do
    for d in $dests; do ours "$d/$n" "$n" && remove "$d/$n"; done
    if has codex && is_generated "$SRC/skills/$n/agents/openai.yaml"; then remove "$SRC/skills/$n/agents/openai.yaml"; fi
    if has gemini && is_generated "$GEMINI_DIR/$n.toml"; then remove "$GEMINI_DIR/$n.toml"; fi
  done
  # Links into this checkout whose skill no longer exists.
  for d in $dests; do
    for entry in "$d"/*; do
      [ -L "$entry" ] || continue
      case "$(readlink "$entry")" in "$SRC/skills/"*) exists "$SRC/skills/$(basename "$entry")" || remove "$entry" ;; esac
    done
  done

  # Restore, newest backup first, every backed-up path that is free again and belongs to the selection.
  [ -d "$BACKUP_ROOT" ] || return 0
  for bdir in $(ls -1d "$BACKUP_ROOT"/*/ 2>/dev/null | sort -r); do
    manifest="$bdir/manifest.tsv"
    [ -f "$manifest" ] || continue
    while IFS="$(printf '\t')" read -r path rest; do
      case "$rest" in *$'\t'restored) continue ;; esac
      case "$restored" in *"|$path|"*) continue ;; esac
      relevant "$path" || continue
      rel=${path#"$HOME"/}
      occupied "$path" && continue
      exists "$bdir$rel" || continue
      say restore "$(short "$bdir$rel") -> $(short "$path")"
      restored="$restored|$path|"
      [ "$DRY" = 1 ] && continue
      mkdir -p "$(dirname "$path")"
      mv "$bdir$rel" "$path"
      awk -F '\t' -v p="$path" 'BEGIN { OFS = "\t" } $1 == p && $NF != "restored" { $0 = $0 "\trestored" } { print }' \
        "$manifest" > "$manifest.tmp" && mv "$manifest.tmp" "$manifest"
    done < "$manifest"
  done
  return 0
}

# Whether a backed-up path is something this selection of harnesses installs or retires.
relevant() {
  local p=$1 n path who why h
  for n in $skills; do
    for d in $dests; do [ "$p" = "$d/$n" ] && return 0; done
    if has gemini && [ "$p" = "$GEMINI_DIR/$n.toml" ]; then return 0; fi
    while IFS='|' read -r path who why; do
      [ "$p" = "$path" ] || continue
      for h in $who; do has "$h" && return 0; done
    done <<EOF
$(conflicts "$n")
EOF
  done
  return 1
}

# ---------------------------------------------------------------------------------------------------
# --check

do_check() {
  local n d target status problems=0 warnings=0 path who why h dup both=""
  echo "Source: $SRC"
  echo "Harnesses:$selected"
  for n in $skills; do
    echo "$n"
    dup=0
    for d in $dests; do
      target="$d/$n"
      if ours "$target" "$n"; then status=OK; dup=$((dup + 1))
      elif [ -L "$target" ] && [ ! -e "$target" ]; then status="BROKEN (link to $(readlink "$target"))"
      elif [ -L "$target" ]; then status="ELSEWHERE (link to $(readlink "$target"))"
      elif exists "$target"; then status="COPY (not a link to this checkout)"
      else status=MISSING
      fi
      printf '  %-40s %s\n' "$(short "$target")" "$status"
      [ "$status" = OK ] || problems=$((problems + 1))
    done
    if has codex; then
      path="$SRC/skills/$n/agents/openai.yaml"
      if [ ! -f "$path" ]; then status=MISSING
      elif [ "$(cat "$path")" != "$(openai_yaml "$n")" ]; then status="OUTDATED (run $PROG --harness codex)"
      else status=OK
      fi
      printf '  %-40s %s\n' "agents/openai.yaml" "$status"
      [ "$status" = OK ] || problems=$((problems + 1))
    fi
    if has gemini; then
      path="$GEMINI_DIR/$n.toml"
      if [ ! -f "$path" ]; then status=MISSING
      elif [ "$(cat "$path")" != "$(gemini_toml "$n")" ]; then status="OUTDATED or not ours"
      else status=OK
      fi
      printf '  %-40s %s\n' "$(short "$path")" "$status"
      [ "$status" = OK ] || problems=$((problems + 1))
    fi
    while IFS='|' read -r path who why; do
      exists "$path" || continue
      for h in $who; do
        has "$h" || continue
        case "$path" in
          "$HOME/.codex/skills/"*) printf '  %-40s CONFLICT: %s\n' "$(short "$path")" "$why"; problems=$((problems + 1)) ;;
          *) printf '  %-40s WARN: %s\n' "$(short "$path")" "$why"; warnings=$((warnings + 1)) ;;
        esac
        break
      done
    done <<EOF
$(conflicts "$n")
EOF
    [ "$dup" -ge 2 ] && both="$both $n"
  done
  if [ -n "$both" ]; then
    echo "WARN: in both ~/.claude/skills and ~/.agents/skills:$both. Copilot in VS Code and Cursor read both"
    echo "      folders and may list these skills twice."
    warnings=$((warnings + 1))
  fi
  for d in $dests; do
    for target in "$d"/*; do
      [ -L "$target" ] || continue
      case "$(readlink "$target")" in
        "$SRC/skills/"*) exists "$SRC/skills/$(basename "$target")" || {
          printf '  %-40s STALE: the skill no longer exists in the source\n' "$(short "$target")"
          problems=$((problems + 1)); } ;;
      esac
    done
  done
  echo "$problems problem(s), $warnings warning(s)."
  [ "$problems" = 0 ]
}

# ---------------------------------------------------------------------------------------------------
# Main: plan with DRY=1, confirm, then apply.

if [ "$mode" = check ]; then do_check; exit $?; fi

echo "Source: $SRC"
echo "Harnesses:$selected"
echo "Plan ($mode$([ "$retire" = 1 ] && echo ', retire conflicts')):"
if [ "$mode" = install ]; then do_install; else do_uninstall; fi
if [ "$changes" = 0 ]; then echo "  nothing to do"; exit 0; fi
[ "$dry" = 1 ] && exit 0

if [ "$yes" != 1 ]; then
  [ -t 0 ] || die "stdin is not a terminal: pass --yes to apply"
  printf 'Apply these %s action(s)? [y/N] ' "$changes"
  read -r answer
  case "$answer" in y|Y|yes|YES) ;; *) echo "Cancelled."; exit 0 ;; esac
fi

DRY=0 changes=0 removed=''
echo "Applying:"
if [ "$mode" = install ]; then do_install; else do_uninstall; fi
[ -f "$BACKUP/manifest.tsv" ] && echo "Backup: $(short "$BACKUP")"
echo "Done."
